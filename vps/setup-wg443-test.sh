#!/bin/bash
# setup-wg443-test.sh — WireGuard TEST server on UDP 443 for the FirstByte SG box.
#
# WHY: WireGuard on UDP 51820 (and a 4500 redirect) is blackholed on the
# user's carriers — the official WireGuard app shows rx: 0 B (handshake
# responses never come back), while TUIC on UDP 443 works end-to-end.
# This kit tests the ONE remaining variable: WireGuard itself on UDP 443,
# the port whose return path is proven (by TUIC on the JP box).
#
# Adds ONE wg-quick interface "wg-443" on UDP 443 with a single client.
# It touches nothing else on the box (Xray SG2/SG2-WS/free-VLESS, Caddy,
# gs-meter, gs-udpgw and the Temp Mail stack are left alone) and ABORTS
# if UDP 443 is already bound.
#
# Client Address is 10.66.67.2/32 (Xray's wireguard outbound rejects a
# non-/32 interface address at startup). Tunnel net is 10.66.67.0/24.
#
# Re-running ROTATES all keys — the old client config/link stop working.
# Remove:  systemctl disable --now wg-quick@wg-443
#          rm /etc/wireguard/wg-443.conf /etc/sysctl.d/99-wg-443.conf /root/my-wg443-test.txt
set -e

PORT=443
IFACE=wg-443
SERVER_IP="46.8.125.49"
CLIENT_IP="10.66.67.2"

echo "=== WireGuard-on-443 TEST server (UDP $PORT) ==="
[ "$(id -u)" = "0" ] || { echo "!! Run as root. Aborting."; exit 1; }

# 1. Tools.
if ! command -v wg >/dev/null 2>&1; then
  echo "-- installing wireguard-tools..."
  export DEBIAN_FRONTEND=noninteractive
  apt-get update -qq
  apt-get install -y -qq wireguard-tools iptables >/dev/null
fi
command -v iptables >/dev/null 2>&1 || { echo "!! iptables missing (needed for NAT). Aborting."; exit 1; }

# 2. Port must be free (UDP only — Caddy's TCP 443 does not conflict).
if ss -lun | grep -q ":$PORT "; then
  echo "!! UDP $PORT is already in use. Aborting (nothing changed):"
  ss -lunp | grep ":$PORT " || true
  exit 1
fi

# 3. Keys.
umask 077
SERVER_PRIV=$(wg genkey); SERVER_PUB=$(printf '%s' "$SERVER_PRIV" | wg pubkey)
CLIENT_PRIV=$(wg genkey); CLIENT_PUB=$(printf '%s' "$CLIENT_PRIV" | wg pubkey)

# 4. Forwarding + egress interface (for the NAT rule).
EGRESS=$(ip route get 1.1.1.1 2>/dev/null | grep -oP 'dev \K\S+' | head -1)
[ -n "$EGRESS" ] || EGRESS=eth0
echo "net.ipv4.ip_forward=1" > /etc/sysctl.d/99-wg-443.conf
sysctl -p /etc/sysctl.d/99-wg-443.conf >/dev/null
echo "-- egress interface: $EGRESS"

# 5. Server config (PostUp/PostDown manage ONLY this kit's NAT rule).
mkdir -p /etc/wireguard
cat > /etc/wireguard/$IFACE.conf <<EOF
[Interface]
PrivateKey = $SERVER_PRIV
Address = 10.66.67.1/24
ListenPort = $PORT
PostUp = iptables -t nat -A POSTROUTING -s 10.66.67.0/24 -o $EGRESS -j MASQUERADE
PostDown = iptables -t nat -D POSTROUTING -s 10.66.67.0/24 -o $EGRESS -j MASQUERADE

[Peer]
PublicKey = $CLIENT_PUB
AllowedIPs = $CLIENT_IP/32
EOF
chmod 600 /etc/wireguard/$IFACE.conf

# Firewall: open the port only when ufw is active.
if command -v ufw >/dev/null 2>&1 && ufw status | grep -qi "status: active"; then
  ufw allow $PORT/udp >/dev/null || true
  echo "-- ufw: $PORT/udp allowed"
fi

# 6. Start (enable --now does not restart a running service, so restart explicitly).
systemctl enable --now wg-quick@$IFACE >/dev/null 2>&1 || true
systemctl restart wg-quick@$IFACE
sleep 1
systemctl is-active wg-quick@$IFACE
wg show $IFACE | sed -n '1,8p'

# 7. Client outputs.
urlenc() { python3 -c "import urllib.parse,sys; print(urllib.parse.quote(sys.argv[1], safe=''))" "$1"; }
CLIENT_CONF="[Interface]
PrivateKey = $CLIENT_PRIV
Address = $CLIENT_IP/32
DNS = 1.1.1.1

[Peer]
PublicKey = $SERVER_PUB
Endpoint = $SERVER_IP:$PORT
AllowedIPs = 0.0.0.0/0"
WG_LINK="wireguard://$CLIENT_PRIV@$SERVER_IP:$PORT?publickey=$(urlenc "$SERVER_PUB")&address=$CLIENT_IP/32&dns=1.1.1.1&mtu=1280#WG-443-TEST"

{
  echo "# WireGuard-on-443 TEST client — generated by setup-wg443-test.sh"
  echo "# Import the .conf into the official WireGuard app (or paste it), or import the link."
  echo ""
  echo "----- client .conf -----"
  echo "$CLIENT_CONF"
  echo ""
  echo "----- wireguard:// link -----"
  echo "$WG_LINK"
} > /root/my-wg443-test.txt
chmod 600 /root/my-wg443-test.txt

echo ""
echo "==================== CLIENT .conf (official WireGuard app) ===================="
echo "$CLIENT_CONF"
echo ""
echo "==================== wireguard:// LINK ===================="
echo "$WG_LINK"
echo "==============================================================================="
echo "(also saved to /root/my-wg443-test.txt)"
echo "Test: import in the official app -> connect on MOBILE DATA -> My IP must show $SERVER_IP."
echo "Decisive readout: tunnel screen must show a Latest handshake and rx > 0."
